const FUENTES = { normal: { g: LETRA, alto: 7 }, mini: { g: MINI, alto: 5 }, gorda: { g: GORDA, alto: 9 } };
const limpiaTexto = s => String(s).toUpperCase().replace(/…/g, '...').replace(/[“”]/g, '"').replace(/[‘’]/g, "'").replace(/—|–/g, '-');
// el texto tal como lo puede escribir cada letra (las cifras gordas no pasan a mayúsculas)
function preparaTexto(s, fuente) {
  if (fuente === 'gorda') return String(s);
  const t = limpiaTexto(s);
  return fuente === 'mini' ? [...t].map(ch => QUITA_TILDE[ch] || ch).join('') : t;
}
const glifo = (ch, fuente) => { const G = FUENTES[fuente].g; return G[ch] || G['?'] || G[' ']; };
function anchoTexto(s, esc = 1, fuente = 'normal') {
  let w = 0;
  for (const ch of preparaTexto(s, fuente)) w += glifo(ch, fuente)[0].length + 1;
  return Math.max(0, w - 1) * esc;
}
// parte un texto en líneas que caben en «ancho» píxeles
function envuelve(s, ancho, esc = 1, fuente = 'normal') {
  const out = [];
  for (const parrafo of String(s).split('\n')) {
    let linea = '';
    for (const pal of parrafo.split(' ')) {
      const prueba = linea ? linea + ' ' + pal : pal;
      if (anchoTexto(prueba, esc, fuente) <= ancho || !linea) linea = prueba;
      else { out.push(linea); linea = pal; }
    }
    out.push(linea);
  }
  return out;
}

// colores de rótulo: [arriba, medio, abajo]
const ORO_ROTULO = ['#fff7b8', '#ffd23c', '#f08a1c'], BLANCO_ROTULO = ['#ffffff', '#e8eeff', '#a9b8e6'], ROJO_ROTULO = ['#ffd0a8', '#ff6a3c', '#c8201c'];
