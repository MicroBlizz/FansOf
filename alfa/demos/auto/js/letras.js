const TEXTO_CACHE = new Map();
// el texto en un lienzo propio. c: un color o tres [arriba, medio, abajo]; borde: color del contorno (null = sin); sombra: color
function lienzoTexto(s, o = {}) {
  const fuente = o.fuente || 'normal', esc = o.esc || 1, col = o.c || '#fff6ea', borde = o.borde === undefined ? TINTA : o.borde, sombra = o.sombra === undefined ? borde : o.sombra;
  const clave = [s, fuente, esc, col, borde, sombra].join('|');
  let c = TEXTO_CACHE.get(clave);
  if (c) return c;
  if (TEXTO_CACHE.size > 800) TEXTO_CACHE.clear();
  const t = preparaTexto(s, fuente), F_ = FUENTES[fuente], pad = borde ? 1 : 0, arriba = fuente === 'gorda' ? 0 : 2;
  const w = anchoTexto(s, 1, fuente), W = (w + 2) * esc + pad * 2, H = (F_.alto + arriba + 2) * esc + pad * 2 + 1;
  c = document.createElement('canvas'); c.width = Math.max(1, W); c.height = H;
  const g = c.getContext('2d'), pix = [];
  let x = 0;
  for (const ch of t) {
    const gl = glifo(ch, fuente);
    gl.forEach((fila, r) => { for (let k = 0; k < fila.length; k++) if (fila[k] === '#') pix.push([x + k, r]); });
    if (gl.marca) for (const [r, k] of gl.marca) pix.push([x + k, r]);
    x += gl[0].length + 1;
  }
  const ox = pad, oy = pad + arriba * esc;
  if (borde) {
    g.fillStyle = borde;
    for (const [px, py] of pix) g.fillRect(ox + px * esc - 1, oy + py * esc - 1, esc + 2, esc + 2);
  }
  if (sombra) { g.fillStyle = sombra; for (const [px, py] of pix) g.fillRect(ox + px * esc - (borde ? 1 : 0), oy + py * esc + esc, esc + (borde ? 2 : 0), 1 + (borde ? 1 : 0)); }
  for (const [px, py] of pix) {
    g.fillStyle = typeof col === 'string' ? col : col[py < 0 ? 0 : Math.min(2, Math.floor(py * 3 / F_.alto))];
    g.fillRect(ox + px * esc, oy + py * esc, esc, esc);
  }
  c.ox = ox; c.oy = oy;
  TEXTO_CACHE.set(clave, c);
  return c;
}
// escribe en (x, y) = esquina de arriba de la letra. o: { c, esc, borde, sombra, fuente: 'normal' | 'mini' | 'gorda', alin: 'izq' | 'centro' | 'der' }
// Devuelve el ancho
function escribe(ctx, s, x, y, o = {}) {
  const c = lienzoTexto(s, o), w = anchoTexto(s, o.esc || 1, o.fuente || 'normal');
  let X = Math.round(x);
  if (o.alin === 'centro') X = Math.round(x - w / 2); else if (o.alin === 'der') X = Math.round(x - w);
  ctx.drawImage(c, X - c.ox, Math.round(y) - c.oy);
  return w;
}
