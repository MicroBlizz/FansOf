function anchoMini(t) { let w = 0; for (const ch of t) w += (ch === ' ' ? 2 : (MINI[ch] || MINI['-'])[0].length) + 1; return Math.max(0, w - 1); }
function escribeMini(ctx, t, x, y, color = '#ffffff', sombra = null, alinear = 'izq') {
  if (alinear === 'der') x -= anchoMini(t); else if (alinear === 'centro') x -= Math.floor(anchoMini(t) / 2);
  const pasa = (col, dx, dy) => {
    ctx.fillStyle = col;
    let cx = x;
    for (const ch of t) {
      if (ch === ' ') { cx += 3; continue; }
      const g = MINI[ch] || MINI['-'];
      g.forEach((f, j) => { for (let i = 0; i < f.length; i++) if (f[i] === '#') ctx.fillRect(cx + i + dx, y + j + dy, 1, 1); });
      cx += g[0].length + 1;
    }
  };
  if (sombra) pasa(sombra, 1, 1);
  pasa(color, 0, 0);
}

/* ---------- cifras gordas con borde (el daño que salta) ---------- */
function escribeGordo(ctx, t, x, y, color = '#ffffff', borde = '#101438') {
  const pix = [];
  let cx = 0;
  for (const ch of t) {
    const g = LETRAS[ch];
    g.forEach((f, j) => { for (let i = 0; i < f.length; i++) if (f[i] === '#') { pix.push([cx + i, j]); pix.push([cx + i + 1, j]); } });
    cx += g.find(f => f.length).length + 2;
  }
  const w = cx - 1;
  x -= Math.floor(w / 2);
  ctx.fillStyle = borde;
  for (const [i, j] of pix) ctx.fillRect(x + i - 1, y + j - 1, 3, 3);
  ctx.fillStyle = color;
  for (const [i, j] of pix) ctx.fillRect(x + i, y + j, 1, 1);
  ctx.fillStyle = '#fff6c0';
  for (const [i, j] of pix) if (j < 2) ctx.fillRect(x + i, y + j, 1, 1);
}
