// letras con tilde: la base y la marca encima (filas por encima de la letra)
const TILDES = { 'á': 'a', 'é': 'e', 'í': 'ı', 'ó': 'o', 'ú': 'u', 'Á': 'A', 'É': 'E', 'Í': 'I', 'Ó': 'O', 'Ú': 'U', 'ü': 'u' };
LETRAS['ı'] = L(2, ['#', '#', '#', '#', '#']);
function glifo(ch) {
  if (LETRAS[ch]) return LETRAS[ch];
  const base = TILDES[ch];
  if (!base) return LETRAS['?'];
  const g = LETRAS[base].slice(), w = g.find(f => f.length).length, alto = g.findIndex(f => f.length);
  const fila = (cols) => Array.from({ length: w }, (_, i) => cols.includes(i) ? '#' : '.').join('');
  const mitad = Math.floor(w / 2);
  const marca = ch === 'ü' ? [fila([mitad - 1, mitad + 1])] : [fila([Math.min(w - 1, mitad + 1)]), fila([mitad])];
  const r = g.map(f => f);
  if (alto >= marca.length) { for (let k = 0; k < marca.length; k++) r[alto - marca.length + k] = marca[k]; return r; }
  r.arriba = marca;   // mayúsculas: la tilde va por encima de la fila 0
  return r;
}
const anchoGlifo = ch => ch === ' ' ? 3 : glifo(ch).find(f => f && f.length).length;
function anchoTexto(t) { let w = 0; for (const ch of t) w += anchoGlifo(ch) + 1; return Math.max(0, w - 1); }

// escribe con sombra abajo a la derecha; (x, y) = arriba a la izquierda de las mayúsculas
function escribe(ctx, t, x, y, color = '#ffffff', sombra = '#101438', alinear = 'izq') {
  if (alinear === 'der') x -= anchoTexto(t); else if (alinear === 'centro') x -= Math.floor(anchoTexto(t) / 2);
  const pasa = (col, dx, dy) => {
    ctx.fillStyle = col;
    let cx = x;
    for (const ch of t) {
      if (ch === ' ') { cx += 4; continue; }
      const g = glifo(ch);
      g.forEach((f, j) => { for (let i = 0; i < f.length; i++) if (f[i] === '#') ctx.fillRect(cx + i + dx, y + j + dy, 1, 1); });
      if (g.arriba) g.arriba.forEach((f, j) => { for (let i = 0; i < f.length; i++) if (f[i] === '#') ctx.fillRect(cx + i + dx, y - g.arriba.length + j + dy, 1, 1); });
      cx += g.find(f => f && f.length).length + 1;
    }
  };
  if (sombra) pasa(sombra, 1, 1);
  pasa(color, 0, 0);
}

