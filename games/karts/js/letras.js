// letras con tilde: la base y la marca encima (en las mayúsculas, dos filas por encima de la fila 0)
const TILDES = { 'á': 'a', 'é': 'e', 'í': 'ı', 'ó': 'o', 'ú': 'u', 'Á': 'A', 'É': 'E', 'Í': 'I', 'Ó': 'O', 'Ú': 'U', 'ü': 'u', 'Ñ': 'N' };
const GLIFOS = {};
function glifo(ch) {
  if (GLIFOS[ch]) return GLIFOS[ch];
  const base = TILDES[ch], filas = (base ? LETRAS[base] : LETRAS[ch]) || LETRAS['?'];
  const w = filas.find(f => f.length).length, alto = filas.findIndex(f => f.length), pts = [];
  filas.forEach((f, j) => { for (let i = 0; i < f.length; i++) if (f[i] === '#') pts.push([i, j]); });
  if (base) {
    const m = Math.floor(w / 2), y0 = alto >= 2 ? alto - 2 : -2;
    if (ch === 'ü') { pts.push([m - 1, y0 + 1], [m + 1, y0 + 1]); } else if (ch === 'Ñ') { for (let i = 1; i < w - 1; i++) pts.push([i, -2]); }
    else if (ch === 'í') { pts.push([1, 0]); return (GLIFOS[ch] = { w: 2, pts }); }   // la i es tan estrecha que su tilde va al lado
    else { pts.push([Math.min(w - 1, m + 1), y0], [m, y0 + 1]); }
  }
  return (GLIFOS[ch] = { w, pts });
}
function anchoTextoPx(t, esc = 1) { let w = 0; for (const ch of t) w += (ch === ' ' ? 3 : glifo(ch).w) + 1; return Math.max(0, w - 1) * esc; }

// el dibujito de una letra con su color, su sombra (abajo a la derecha) o su borde, a un tamaño: se hace una vez y se guarda
const SELLOS_LETRA = new Map();
function selloLetra(ch, color, sombra, borde, esc) {
  const k = ch + color + (sombra || '') + '|' + (borde || '') + esc;
  let s = SELLOS_LETRA.get(k);
  if (s) return s;
  const g = glifo(ch), [c, x] = lienzo(g.w * esc + 2 + esc, 11 * esc + 2 + esc);
  const pon = (col, dx, dy, gordo) => { x.fillStyle = col; for (const [i, j] of g.pts) x.fillRect(1 + i * esc + dx - gordo, 1 + (j + 2) * esc + dy - gordo, esc + 2 * gordo, esc + 2 * gordo); };
  if (borde) pon(borde, 0, 0, 1);
  if (sombra) pon(sombra, esc, esc, 0);
  pon(color, 0, 0, 0);
  s = { c, w: g.w };
  SELLOS_LETRA.set(k, s);
  return s;
}
// escribe en (x, y) = arriba a la izquierda de las mayúsculas. al: 'izq', 'centro' o 'der'. Con `borde`, la letra lleva contorno.
function escribePx(ctx, t, x, y, color = '#ffffff', sombra = '#1c1028', al = 'izq', esc = 1, borde = null) {
  t = String(t);
  if (al === 'der') x -= anchoTextoPx(t, esc); else if (al === 'centro') x -= Math.floor(anchoTextoPx(t, esc) / 2);
  for (const ch of t) {
    if (ch === ' ') { x += 4 * esc; continue; }
    const s = selloLetra(ch, color, sombra, borde, esc);
    ctx.drawImage(s.c, x - 1, y - 2 * esc - 1);
    x += (s.w + 1) * esc;
  }
}
const escribeB = (ctx, t, x, y, color = '#ffffff', borde = '#1c1028', al = 'izq', esc = 1) => escribe(ctx, t, x, y, color, null, al, esc, borde);
// parte un texto en líneas que quepan en `ancho` píxeles
function lineas(t, ancho, esc = 1) {
  const sal = []; let lin = '';
  for (const pal of String(t).split(' ')) {
    const prueba = lin ? lin + ' ' + pal : pal;
    if (lin && anchoTexto(prueba, esc) > ancho) { sal.push(lin); lin = pal; } else lin = prueba;
  }
  if (lin) sal.push(lin);
  return sal;
}
// (las frases largas van con la letra de cuerpo, Baloo 2: letras-nuevas.js)
function escribeLineas(ctx, t, x, y, ancho, color, sombra, al = 'izq', salto = 11) {
  const antes = LETRA_CUERPO; LETRA_CUERPO = true;
  try {
    const ls = lineas(t, ancho);
    ls.forEach((l, i) => escribe(ctx, l, x, y + i * salto, color, sombra, al));
    return ls.length;
  } finally { LETRA_CUERPO = antes; }
}

